const { contextBridge, ipcRenderer, webUtils } = require('electron');

const invoke = (ch, arg) => ipcRenderer.invoke(ch, arg);

contextBridge.exposeInMainWorld('api', {
  getStore: () => invoke('store:get'),
  profiles: {
    add: data => invoke('profiles:add', data),
    update: (id, patch) => invoke('profiles:update', { id, patch }),
    remove: id => invoke('profiles:remove', id),
    setActive: id => invoke('profiles:setActive', id),
    status: id => invoke('profiles:status', id),
    models: (id, refresh = false) => invoke('profiles:models', { id, refresh }),
    login: id => invoke('profiles:login', id),
    loginConsole: id => invoke('profiles:loginConsole', id),
    loginCancel: id => invoke('profiles:loginCancel', id),
    logout: id => invoke('profiles:logout', id),
    openTerminal: (id, cwd) => invoke('profiles:openTerminal', { id, cwd }),
  },
  favorites: {
    add: () => invoke('favorites:add'),
    remove: p => invoke('favorites:remove', p),
  },
  projects: {
    add: data => invoke('projects:add', data),
    update: (id, patch) => invoke('projects:update', { id, patch }),
    remove: id => invoke('projects:remove', id),
    setActive: id => invoke('projects:setActive', id),
    reorder: ids => invoke('projects:reorder', ids),
    pickIcon: () => invoke('projects:pickIcon'),
    groupAdd: data => invoke('projects:groupAdd', data),
    groupUpdate: (id, patch) => invoke('projects:groupUpdate', { id, patch }),
    groupRemove: id => invoke('projects:groupRemove', id),
  },
  pickFolder: () => invoke('dialog:pickFolder'),
  setSettings: patch => invoke('settings:set', patch),
  pickClaude: () => invoke('settings:pickClaude'),
  resetBypassWarning: () => invoke('settings:resetBypassWarning'),
  history: {
    list: profileId => invoke('history:list', profileId),
    loadSession: data => invoke('history:loadSession', data),
    search: (profileId, query) => invoke('history:search', { profileId, query }),
  },
  session: {
    send: (tab, content) => invoke('session:send', { tab, content }),
    confirmBypass: tabId => invoke('session:confirmBypass', tabId),
    respond: (tabId, requestId, response) => invoke('session:respond', { tabId, requestId, response }),
    interrupt: tabId => invoke('session:interrupt', tabId),
    restart: tabId => invoke('session:restart', tabId),
    close: tabId => invoke('session:close', tabId),
    moveProfile: data => invoke('session:moveProfile', data),
  },
  openPath: p => invoke('shell:openPath', p),
  focusWindow: () => invoke('app:focus'),
  attention: () => invoke('app:attention'),
  readTaskOutput: file => invoke('task:readOutput', file),
  copyText: text => invoke('clipboard:write', text),
  pickAttachments: () => invoke('attach:pick'),
  // Pfad einer per Drag & Drop abgelegten Datei (nur für vom Nutzer abgelegte File-Objekte)
  pathForFile: file => { try { return webUtils.getPathForFile(file); } catch { return ''; } },
  onEvent: cb => ipcRenderer.on('claude:event', (_e, d) => cb(d)),
  onUsage: cb => ipcRenderer.on('usage:update', (_e, d) => cb(d)),
  onLogin: cb => ipcRenderer.on('login:update', (_e, d) => cb(d)),
  notify: data => invoke('notify:show', data),
  extensions: {
    list: profileId => invoke('ext:list', profileId),
    action: (profileId, action, id) => invoke('ext:action', { profileId, action, id }),
  },
  remote: {
    info: () => invoke('remote:info'),
    hostSet: data => invoke('remote:hostSet', data),
    pairStart: () => invoke('remote:pairStart'),
    pairCancel: () => invoke('remote:pairCancel'),
    deviceSet: data => invoke('remote:deviceSet', data),
    deviceRemove: id => invoke('remote:deviceRemove', id),
    pair: data => invoke('remote:pair', data),
    hostRemove: id => invoke('remote:hostRemove', id),
    // Anfrage für einen Chat eines Haupt-PCs (nur freigegebene Kanäle, siehe main.js REMOTE_CALLS)
    call: (host, ch, args) => ipcRenderer.invoke('remote:call', host, ch, args),
    onStatus: cb => ipcRenderer.on('remote:status', (_e, d) => cb(d)),
    onTabs: cb => ipcRenderer.on('remote:tabs', (_e, d) => cb(d)),
    publishTabs: list => invoke('tabs:publish', list),
  },
  onNotifyClick: cb => ipcRenderer.on('notify:click', (_e, tabId) => cb(tabId)),
  update: {
    state: () => ipcRenderer.invoke('update:state'),
    check: () => ipcRenderer.invoke('update:check'),
    download: () => ipcRenderer.invoke('update:download'),
    install: () => ipcRenderer.invoke('update:install'),
    onStatus: cb => ipcRenderer.on('update:status', (_e, st) => cb(st)),
  },
});
