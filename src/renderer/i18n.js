// Swapline – Sprache der Oberfläche (Deutsch / Englisch). Deutsch ist die Quellsprache:
// Schlüssel im Wörterbuch EN ist immer der deutsche Text, wie er in app.js bzw. index.html steht.
// Fehlt eine Übersetzung, erscheint der deutsche Text (tests/run.js meldet fehlende Schlüssel).
'use strict';

let LANG = 'de';

// pref: 'de' | 'en' | 'auto' (auto = Sprache des Systems; Deutsch nur, wenn sie mit „de“ beginnt)
function setLang(pref) {
  LANG = pref === 'de' || pref === 'en' ? pref : (String(navigator.language || '').toLowerCase().startsWith('de') ? 'de' : 'en');
  document.documentElement.lang = LANG;
  return LANG;
}
// Locale für Datum und Uhrzeit (en-GB: 24-Stunden-Format)
const locale = () => (LANG === 'en' ? 'en-GB' : 'de-DE');

// Markiert einen Text für die Übersetzung, ohne ihn schon zu übersetzen (für Konstanten, die vor
// setLang() entstehen). Übersetzt wird erst beim Anzeigen mit _(text).
const N_ = s => s;

// Text in der aktuellen Sprache; {name} wird aus vars ersetzt (auch im deutschen Text)
function _(de, vars) {
  if (typeof de !== 'string') return de;
  let s = LANG === 'en' && Object.prototype.hasOwnProperty.call(EN, de) ? EN[de] : de;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (Object.prototype.hasOwnProperty.call(vars, k) ? String(vars[k]) : m));
  return s;
}

// Feste Texte aus index.html übersetzen: Inhalt von Elementen mit data-i18n sowie die Attribute
// title, placeholder und aria-label. Der deutsche Ausgangstext wird gemerkt, damit mehrfaches Aufrufen
// (z. B. Sprachwechsel im Test) funktioniert. Hat die App einen Wert inzwischen selbst geändert,
// gilt der neue Wert als Ausgangstext.
const I18N_ATTRS = ['title', 'placeholder', 'aria-label'];
const i18nOrig = new WeakMap(); // Element -> { [attr | '#text']: { src, out } }
function translateStatic(root = document) {
  const apply = (node, slot, current, write) => {
    const mem = i18nOrig.get(node) || {};
    const prev = mem[slot];
    const src = prev && prev.out === current ? prev.src : current;
    const out = _(src);
    mem[slot] = { src, out };
    i18nOrig.set(node, mem);
    if (out !== current) write(out);
  };
  root.querySelectorAll('[data-i18n]').forEach(node => apply(node, '#text', node.textContent.trim(), v => { node.textContent = v; }));
  for (const attr of I18N_ATTRS) {
    root.querySelectorAll('[' + attr + ']').forEach(node => {
      const v = node.getAttribute(attr);
      if (v) apply(node, attr, v, out => node.setAttribute(attr, out));
    });
  }
}

